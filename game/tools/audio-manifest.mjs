// Writes src/audio/manifest.ts from whatever OGG files sit in public/audio/{sfx,music}/.
// Run after (re)generating samples: `node tools/audio-manifest.mjs`. Trigger name = file name without
// a trailing variant digit (mutter1.ogg, mutter2.ogg -> 'mutter' with two files, picked at random).
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const pub = join('public', 'audio');
const list = (sub) => {
  try {
    return readdirSync(join(pub, sub)).filter((f) => f.endsWith('.ogg')).sort();
  } catch {
    return [];
  }
};

// loudness trims on top of the -16 LUFS masters so categories sit together (UI quiet, beds quieter)
const GAIN = {
  ui: 0.55, loop: 0.38, ambience: 0.32, voice: 0.85, impact: 0.9, sting: 0.75, default: 0.8,
};
const CATEGORY = {
  tap: 'ui', open: 'ui', close: 'ui', page: 'ui', rotate: 'ui', error: 'ui', place: 'ui', sell: 'ui',
  ambience: 'ambience',
  groan: 'voice', mutter: 'voice', scream: 'voice', groupScream: 'voice', hungry: 'voice', refresh: 'voice', snore: 'voice',
  hit: 'impact', punch: 'impact', whack: 'impact', knockdown: 'impact', stomp: 'impact', chomp: 'impact',
  levelUp: 'sting', raidWin: 'sting', raidLose: 'sting', panic: 'sting', rareArrival: 'sting', summon: 'sting', expand: 'sting',
};
const LOOPS = new Set(['ambience', 'cookStove', 'cookGrill', 'cookSmoker', 'cookFryer', 'cookCauldron', 'cookKiln', 'cookPit', 'cookTomb']);

const sfx = {};
let bytes = 0;
for (const f of list('sfx')) {
  const name = f.replace(/\.ogg$/, '').replace(/\d+$/, '');
  (sfx[name] ??= []).push(`sfx/${f}`);
  bytes += statSync(join(pub, 'sfx', f)).size;
}
let sfxBytes = bytes;
if (sfxBytes > 2.5 * 1024 * 1024) throw new Error(`sfx set is ${(sfxBytes / 1024).toFixed(0)} KB, budget 2560 KB`);
const music = {};
for (const f of list('music')) {
  music[f.replace(/\.ogg$/, '')] = `music/${f}`;
  const sz = statSync(join(pub, 'music', f)).size;
  if (sz > 1.5 * 1024 * 1024) throw new Error(`${f} is ${(sz / 1024).toFixed(0)} KB, budget 1536 KB`);
  bytes += sz;
}

const lines = [
  '// Generated by tools/audio-manifest.mjs from public/audio/ — do not edit by hand.',
  `// ${Object.keys(sfx).length} sfx names, ${Object.keys(music).length} music tracks, ${(bytes / 1024).toFixed(0)} KB.`,
  '',
  'export interface SampleDef {',
  '  /** one or more files (variants are picked at random), relative to SAMPLE_DIR */',
  '  files: string[];',
  '  /** loudness trim on top of the -16 LUFS master */',
  '  gain: number;',
  '  loop?: boolean;',
  '}',
  '',
  "export const SAMPLE_DIR = 'audio/';",
  '',
  'export const SFX_SAMPLES: Record<string, SampleDef> = {',
  ...Object.entries(sfx).map(([n, files]) => {
    const cat = LOOPS.has(n) && n !== 'ambience' ? 'loop' : CATEGORY[n] ?? 'default';
    return `  ${n}: { files: [${files.map((f) => `'${f}'`).join(', ')}], gain: ${GAIN[cat]}${LOOPS.has(n) ? ', loop: true' : ''} },`;
  }),
  '};',
  '',
  'export const MUSIC_SAMPLES: Record<string, string> = {',
  ...Object.entries(music).map(([n, f]) => `  ${n}: '${f}',`),
  '};',
  '',
];
writeFileSync(join('src', 'audio', 'manifest.ts'), lines.join('\n'));
console.log(`src/audio/manifest.ts: ${Object.keys(sfx).length} sfx, ${Object.keys(music).length} music, ${(bytes / 1024).toFixed(0)} KB`);
